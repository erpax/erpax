#!/usr/bin/env node
/**
 * Build one @erpax/<atom> workspace package from the live src tree.
 *
 * Usage: node packages/build.mjs <atom> | all
 *
 * Pipeline per package:
 *   1. esbuild bundles src/<atom>/index.ts → dist/index.js (ESM). `@/x` resolves
 *      into src/; every bare specifier stays external and is COMPUTED into the
 *      package's dependencies/peerDependencies from the root package.json.
 *   2. tsc emits declarations for the type closure → dist/types/** (rootDir src),
 *      then `@/x` specifiers in the emitted .d.ts are rewritten to relative paths.
 *   3. Ratchet: the runtime closure's atom count must not exceed
 *      package.json `erpax.closureCeiling` — entanglement growth fails closed.
 *
 * GENERATED PACKAGES. Every folder in `src/packages` is a package here: `all` first asks
 * `packages/apps.ts` what each folder holds and writes what is missing — the manifest
 * (`packages/<name>/package.json`, at the one shared version), a README, and for an app the entry
 * that carries its collections (`src/packages/<name>/.package.ts`, generated on every build and
 * not committed). Which collections an app carries is computed from the relationship graph, so
 * the package follows the source: nobody lists them.
 *
 * `@erpax/algebra` keeps its own dedicated build (MIT tier, hand-audited surface).
 */
import { build } from 'esbuild'
import { spawnSync } from 'node:child_process'
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs'
import { builtinModules } from 'node:module'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const packagesDir = dirname(fileURLToPath(import.meta.url))
const root = join(packagesDir, '..')
const rootPkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))

/** payload/next/react are host-provided — peers, never bundled deps. */
const PEERS = new Set(['payload', 'next', 'react', 'react-dom'])

/** The one version every package carries — the root package.json's. */
const sharedVersion = rootPkg.version

/** What `src/packages` asks this folder to hold (see packages/apps.ts). */
function generatedPackages() {
  const run = spawnSync(join(root, 'node_modules/.bin/tsx'), [join(packagesDir, 'apps.ts')], { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] })
  if (run.status !== 0) throw new Error(`packages/apps.ts failed: ${(run.stderr || run.stdout).split('\n').slice(0, 5).join(' | ')}`)
  return JSON.parse(run.stdout.trim().split('\n').pop())
}

/** Write what a generated package is missing; the app's entry is rewritten every time. */
function generate() {
  const template = JSON.parse(readFileSync(join(packagesDir, 'access', 'package.json'), 'utf8'))
  const names = []
  for (const g of generatedPackages()) {
    names.push(g.name)
    const pkgDir = join(packagesDir, g.name)
    mkdirSync(pkgDir, { recursive: true })
    const entryFile = g.app ? `packages/${g.name}/.package.ts` : `packages/${g.name}/index.ts`
    if (g.app) {
      const lines = g.app.collections.map((c) => `import ${c.isDefault ? c.name : `{ ${c.name} }`} from '${c.from}'`)
      writeFileSync(
        join(root, 'src', entryFile),
        `// GENERATED by packages/build.mjs from src/packages/${g.name} — not committed, do not edit.
import type { CollectionConfig, Plugin } from 'payload'
import { appPlugin } from '@/packages/engine'
import { ${g.app.export} } from '@/packages/${g.name}'
${lines.join('\n')}

/** The app: its name and the collections that define it. */
export const app = ${g.app.export}

/** The collections the relationship graph gives this app. */
export const collections: CollectionConfig[] = [${g.app.collections.map((c) => c.name).join(', ')}]

/** ${g.title} as a Payload plugin: it adds the app's collections under the app's name. */
export const plugin = (): Plugin => appPlugin(app, collections)

export default plugin
`,
      )
    }
    const pkgJsonPath = join(pkgDir, 'package.json')
    if (!existsSync(pkgJsonPath)) {
      const types = `./dist/types/${entryFile.replace(/\.ts$/, '.d.ts')}`
      const pkg = {
        name: `@erpax/${g.name}`,
        version: sharedVersion,
        description: `${g.title} — ${g.about}. ${g.app ? 'An erpax app, delivered as one Payload plugin' : 'Part of erpax'}. CC-BY-NC-ND-4.0, or commercial via license@erpax.com.`,
        license: template.license,
        type: 'module',
        sideEffects: false,
        main: './dist/index.js',
        types,
        exports: { '.': { types, import: './dist/index.js' } },
        files: template.files,
        publishConfig: template.publishConfig,
        repository: { ...template.repository, directory: `packages/${g.name}` },
        homepage: `https://github.com/erpax/erpax/tree/main/packages/${g.name}`,
        engines: template.engines,
        scripts: { build: `node ../build.mjs ${g.name}`, prepublishOnly: `node ../build.mjs ${g.name}` },
        erpax: { generated: true, entryFile },
        keywords: ['payload-cms', 'payload-plugin', 'erpax', g.name],
      }
      writeFileSync(pkgJsonPath, `${JSON.stringify(pkg, null, 2)}\n`)
    }
    const ignore = join(pkgDir, '.gitignore')
    if (!existsSync(ignore)) writeFileSync(ignore, readFileSync(join(packagesDir, 'access', '.gitignore'), 'utf8'))
    const readme = join(pkgDir, 'README.md')
    if (!existsSync(readme)) {
      writeFileSync(
        readme,
        g.app
          ? `# @erpax/${g.name}\n\n${g.title} — ${g.about}. One erpax app, delivered as one Payload plugin.\n\n\`\`\`bash\npnpm add @erpax/${g.name}\n\`\`\`\n\n\`\`\`ts\nimport { buildConfig } from 'payload'\nimport ${g.name} from '@erpax/${g.name}'\n\nexport default buildConfig({\n  plugins: [${g.name}()],\n})\n\`\`\`\n\nThe package is generated from \`src/packages/${g.name}\`. The collections it brings are computed from the relationship graph; \`collections\` lists them and \`app\` names the anchors that define the app.\n`
          : `# @erpax/${g.name}\n\n${g.title} — ${g.about}.\n\n\`\`\`bash\npnpm add @erpax/${g.name}\n\`\`\`\n\nThe package is generated from \`src/packages/${g.name}\`.\n`,
      )
    }
  }
  return names
}

function resolveAlias(spec) {
  const p = join(root, 'src', spec.slice(2))
  for (const c of [p, `${p}.ts`, `${p}.tsx`, join(p, 'index.ts'), join(p, 'index.tsx')]) {
    if (existsSync(c) && statSync(c).isFile()) return c
  }
  return null
}

async function buildOne(atom) {
  const pkgDir = join(packagesDir, atom)
  const pkgJsonPath = join(pkgDir, 'package.json')
  const pkg = JSON.parse(readFileSync(pkgJsonPath, 'utf8'))
  /** where the package's source lives under src/ — its own name unless it says otherwise */
  const source = pkg.erpax?.entry ?? atom
  /** a generated package names its entry file; a hand-kept one is `<source>/index.ts` */
  const entryFile = pkg.erpax?.entryFile ?? `${source}/index.ts`
  const entry = join(root, 'src', entryFile)
  const dist = join(pkgDir, 'dist')
  rmSync(dist, { recursive: true, force: true })

  const externals = new Set()
  const result = await build({
    entryPoints: [entry],
    bundle: true,
    format: 'esm',
    platform: 'node',
    target: 'es2022',
    outfile: join(dist, 'index.js'),
    metafile: true,
    logLevel: 'silent',
    plugins: [
      {
        name: 'erpax-alias-and-external',
        setup(b) {
          b.onResolve({ filter: /^@\// }, (args) => {
            const r = resolveAlias(args.path)
            return r ? { path: r } : { errors: [{ text: `unresolvable alias ${args.path}` }] }
          })
          b.onResolve({ filter: /^[^./]/ }, (args) => {
            externals.add(args.path)
            return { path: args.path, external: true }
          })
        },
      },
    ],
  })

  const closureFiles = Object.keys(result.metafile.inputs)
  const atoms = new Set(
    closureFiles
      .map((f) => relative(join(root, 'src'), join(root, f)))
      .filter((r) => !r.startsWith('..'))
      .map((r) => r.split('/')[0]),
  )
  // a generated package starts at what it measures; from then on the ceiling is a ratchet like any other
  if (pkg.erpax?.generated && typeof pkg.erpax.closureCeiling !== 'number') pkg.erpax.closureCeiling = atoms.size
  const ceiling = pkg.erpax?.closureCeiling ?? 0
  if (atoms.size > ceiling) {
    throw new Error(
      `closure ratchet: ${atom} touches ${atoms.size} atoms > ceiling ${ceiling} — ` +
        `entanglement grew; cut the new edge or raise the ceiling in the same diff`,
    )
  }

  /*
   * THE BYTE RATCHET — because the atom count did not say what it costs.
   *
   * `@erpax/cloudflare` sits at its 73-atom ceiling and ships 5.8 MB, and a consumer calling the
   * simplest thing in it pays all of it. Measured, entry by entry:
   *
   *   @/cloudflare/constants alone          0 KB ·  1 atom
   *   kvGet · kvPut · r2Get · r2Put     5,836 KB · 73 atoms
   *   the whole face                    5,880 KB · 73 atoms
   *
   * One edge does it: `cloudflare/bindings.ts` imports `@/diamond`, which imports
   * `@/readme/compute`, which imports `@/rules` — the entire gate registry, and `typescript` with
   * it. Those diamond-derivation functions SCAN `src/` on disk, so they cannot run in a Worker at
   * all; the package's own runtime half pays 5.8 MB to carry tooling its target runtime cannot
   * execute. Cutting it is a face change (`bindingDiamond` and friends leaving the barrel), which
   * is a decision, not a build flag.
   *
   * So the size is a ratcheted FACT until then: it may fall freely and may not rise. An atom
   * ceiling counts entanglement; this counts what the entanglement weighs.
   */
  const sizeKb = Math.round(statSync(join(dist, 'index.js')).size / 1024)
  const sizeCeiling = pkg.erpax?.sizeCeilingKb ?? Number.POSITIVE_INFINITY
  if (sizeKb > sizeCeiling) {
    throw new Error(
      `size ratchet: ${atom} ships ${sizeKb}KB > ceiling ${sizeCeiling}KB — ` +
        `a consumer pays this on install; cut the edge or raise the ceiling in the same diff`,
    )
  }

  const allRootDeps = { ...rootPkg.devDependencies, ...rootPkg.dependencies }
  const deps = {}
  const peers = {}
  for (const e of [...externals].sort()) {
    if (e.startsWith('node:')) continue
    const name = e.startsWith('@') ? e.split('/').slice(0, 2).join('/') : e.split('/')[0]
    // a Node builtin written without `node:` is not a dependency; a scope with no name
    // (`@payload-config`) is the HOST's path alias, not an npm package — neither can be installed
    if (builtinModules.includes(name) || (name.startsWith('@') && !name.includes('/'))) continue
    const version = allRootDeps[name]
    if (PEERS.has(name)) peers[name] = version ?? '*'
    else if (version) deps[name] = version
    else peers[name] = '*'
  }
  pkg.dependencies = Object.keys(deps).length ? deps : undefined
  pkg.peerDependencies = Object.keys(peers).length ? peers : undefined
  writeFileSync(pkgJsonPath, `${JSON.stringify(pkg, null, 2)}\n`)

  const typesDir = join(dist, 'types')
  const tsconfigPath = join(pkgDir, '.build.tsconfig.json')
  writeFileSync(
    tsconfigPath,
    JSON.stringify(
      {
        compilerOptions: {
          target: 'ES2022',
          module: 'ESNext',
          moduleResolution: 'Bundler',
          jsx: 'react-jsx',
          declaration: true,
          emitDeclarationOnly: true,
          outDir: typesDir,
          rootDir: join(root, 'src'),
          baseUrl: root,
          paths: { '@/*': ['src/*'] },
          strict: true,
          skipLibCheck: true,
          noEmitOnError: false,
        },
        files: [entry],
      },
      null,
      2,
    ),
  )
  const tsc = spawnSync(join(root, 'node_modules/.bin/tsc'), ['-p', tsconfigPath], {
    stdio: 'pipe',
    encoding: 'utf8',
  })
  rmSync(tsconfigPath, { force: true })
  const typesOk = existsSync(join(typesDir, entryFile.replace(/\.tsx?$/, '.d.ts')))
  if (typesOk) rewriteAliasInDts(typesDir)

  copyFileSync(join(root, 'LICENSE'), join(pkgDir, 'LICENSE'))
  const bytes = statSync(join(dist, 'index.js')).size
  return {
    atom,
    files: closureFiles.length,
    atoms: atoms.size,
    kb: Math.round(bytes / 1024),
    externals: externals.size,
    typesOk,
    tscNote: typesOk ? '' : (tsc.stdout || tsc.stderr || '').split('\n')[0],
  }
}

function rewriteAliasInDts(typesDir) {
  const walk = (d) => {
    for (const e of readdirSync(d)) {
      const p = join(d, e)
      if (statSync(p).isDirectory()) walk(p)
      else if (e.endsWith('.d.ts')) {
        const text = readFileSync(p, 'utf8')
        const next = text.replace(/(['"])@\/([^'"]+)\1/g, (_m, q, spec) => {
          let rel = relative(dirname(p), join(typesDir, spec)).replace(/\\/g, '/')
          if (!rel.startsWith('.')) rel = `./${rel}`
          return `${q}${rel}${q}`
        })
        if (next !== text) writeFileSync(p, next)
      }
    }
  }
  walk(typesDir)
}

const target = process.argv[2]
if (!target) {
  console.error('usage: node packages/build.mjs <atom>|all')
  process.exit(1)
}
if (target === 'all') generate()
const targets =
  target === 'all'
    ? readdirSync(packagesDir).filter(
        (e) =>
          e !== 'algebra' &&
          statSync(join(packagesDir, e)).isDirectory() &&
          existsSync(join(packagesDir, e, 'package.json')),
      )
    : [target]

let failed = 0
for (const atom of targets) {
  try {
    const r = await buildOne(atom)
    console.log(
      `✓ @erpax/${r.atom} — ${r.files} files · ${r.atoms} atoms · ${r.kb}KB · ` +
        `${r.externals} externals · types ${r.typesOk ? 'OK' : `FAILED (${r.tscNote})`}`,
    )
    if (!r.typesOk) failed++
  } catch (err) {
    console.error(`✖ @erpax/${atom} — ${err.message.split('\n')[0]}`)
    failed++
  }
}
process.exit(failed ? 1 : 0)
