import { describe, it, expect } from 'vitest'
import { buildAutoGeneratedTools, checkAutoGenerationCoverage } from './auto-generated'
import { agentRegistry } from '@/agent'

const tools = buildAutoGeneratedTools(agentRegistry)
const byName = new Map(tools.map((t) => [t.name, t]))
/** The pair reads no request — the corpus is static — so a null req is honest here. */
const text = async (name: string, args: Record<string, unknown>): Promise<Record<string, unknown>> => {
  const r = await byName.get(name)!.handler(args, null as never)
  return JSON.parse(r.content[0]?.text ?? '{}') as Record<string, unknown>
}

/*
 * THE DISCOVERY PAIR. 2,807 `erpax.auto.skill.<atom>` tools were a CATALOGUE wearing a tool
 * surface: 835 KB of a 968 KB tools/list, which no MCP client can put in front of a model.
 * The capability has to survive the collapse, so each half is exercised here.
 */
describe('mcp/discovery — two tools reach what 2,807 did', () => {
  it('the per-skill tools are gone', () => {
    expect(tools.filter((t) => t.name.startsWith('erpax.auto.skill.'))).toEqual([])
  })

  it('the pair is present', () => {
    expect(byName.has('erpax.skill.list')).toBe(true)
    expect(byName.has('erpax.skill.read')).toBe(true)
  })

  it('list pages, and reports the total so a client knows there is more', async () => {
    const first = await text('erpax.skill.list', { limit: 5 })
    expect((first.skills as unknown[]).length).toBe(5)
    expect(first.total as number).toBeGreaterThan(1000)
    const second = await text('erpax.skill.list', { limit: 5, offset: 5 })
    expect((second.skills as { atom: string }[])[0]!.atom).not.toBe((first.skills as { atom: string }[])[0]!.atom)
  })

  it('RANKS the exact atom first — the first page is the only page a model reads', async () => {
    // Unranked, q='cycle' answered with `active · animal · base`: atoms whose PROSE mentions a
    // cycle, while `rules/cycle` sat further down. Searching descriptions is what makes the pair
    // as findable as named tools were; ranking is what makes it usable.
    const r = await text('erpax.skill.list', { q: 'cycle', limit: 3 })
    expect((r.skills as { atom: string }[])[0]!.atom).toBe('cycle')
  })

  it('read returns what the per-atom tool returned', async () => {
    const r = await text('erpax.skill.read', { atom: 'rules/cycle' })
    expect(r.path).toBe('rules/cycle')
    expect(r.excerptChars as number).toBeGreaterThan(0)
    expect(r.contentUuid).toMatch(/^[0-9a-f-]{36}$/)
  })

  /*
   * LEAVES COLLIDE, and the collision used to eat atoms. The catalogue deduped on the folder
   * leaf, last-write-wins: `cycle` is rules/cycle AND vocabulary/cycle AND water/cycle, so two
   * of the three had no MCP presence at all — 3,414 atoms in the corpus, 2,881 in the
   * catalogue. Keyed by PATH now, and the pair refuses to guess between them.
   */
  it('distinct atoms sharing a leaf are DISTINCT — this used to drop 533 of them', async () => {
    const rules = await text('erpax.skill.read', { atom: 'rules/cycle' })
    const water = await text('erpax.skill.read', { atom: 'water/cycle' })
    expect(rules.path).toBe('rules/cycle')
    expect(water.path).toBe('water/cycle')
    expect(rules.sealedExcerpt).not.toBe(water.sealedExcerpt)
  })

  it('an ambiguous LEAF is refused with its candidates — never a silent wrong atom', async () => {
    const r = await text('erpax.skill.read', { atom: 'cycle' })
    expect(String(r.error)).toContain('LEAF shared by')
    expect(r.candidates as string[]).toContain('rules/cycle')
    expect(r.candidates as string[]).toContain('water/cycle')
  })

  it('list returns the PATH, so a client can tell colliding leaves apart', async () => {
    const r = await text('erpax.skill.list', { q: 'cycle', limit: 50 })
    const paths = (r.skills as { path: string }[]).map((s) => s.path)
    expect(paths).toContain('rules/cycle')
    expect(paths).toContain('water/cycle')
  })

  it('an unknown atom is an error WITH the way out, never a throw', async () => {
    const r = await text('erpax.skill.read', { atom: 'nope/nope' })
    expect(String(r.error)).toContain('nope/nope')
    expect(String(r.hint)).toContain('erpax.skill.list')
  })

  it('Conservation Law 37 still holds — the primitive is covered BY THE PAIR', () => {
    const names = new Set(tools.map((t) => t.name))
    const cov = checkAutoGenerationCoverage(agentRegistry, names)
    expect(cov.violations.filter((v) => v.startsWith('skills:'))).toEqual([])
    expect(cov.counts.skills.tools).toBe(cov.counts.skills.primitive)
  })

  it('and it FAILS when the pair is absent — the law is not satisfied by omission', () => {
    const without = new Set([...tools.map((t) => t.name)].filter((n) => n !== 'erpax.skill.read'))
    const cov = checkAutoGenerationCoverage(agentRegistry, without)
    expect(cov.violations.some((v) => v.startsWith('skills:'))).toBe(true)
  })
})
