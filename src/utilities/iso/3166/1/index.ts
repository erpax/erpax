export type CountryCode = (typeof COUNTRY_CODES)[number]

const COUNTRY_SET: ReadonlySet<string> = new Set(COUNTRY_CODES)

/** Whether a value is one of the ISO 3166-1 alpha-2 codes a country field accepts. */
export const isCountryCode = (value: unknown): value is CountryCode => typeof value === 'string' && COUNTRY_SET.has(value)

const names = (() => {
  try {
    return new Intl.DisplayNames(['en'], { type: 'region' })
  } catch {
    return null
  }
})()

/** The select options: each code, labelled with its English name where the runtime knows it. */
export const countryOptions = COUNTRY_CODES.map((value) => ({ value, label: names?.of(value) ?? value }))
