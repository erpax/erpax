import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
/**
 * skill/router/build/stub — the 265 bytes CI writes, without booting the corpus to write them.
 *
 * The full emit walks every SKILL.md and produces ~80MB, which no Worker can hold; CI and deploy
 * write an EMPTY pool instead so the static import resolves. That stub is 265 fixed bytes, and
 * emitting it cost 6.3s on a CI runner — not because writing is slow, but because the emitter it
 * lived in imports [[aura]], [[navigation]] and the skill upgrade seal at module top level. The
 * stub path needs none of them; ESM evaluates them anyway.
 *
 * So the writer moved here, where the only imports are `node:fs` and `node:path`, and the full
 * emitter calls into it. One spelling of the file's shape, two callers — extracting it would be
 * pointless if the format lived in two places.
 *
 * @see ../index.ts — the full emit that also writes through this
 */

/*
 * NOT exported. An exported constant is seal-debt ([[matrix]]) — the models publish BEHAVIOUR, not
 * literals, and a caller that needs this path gets it back from the write itself (`out`).
 */
const SKILL_INDEX_OUT = 'src/skill/router/skills.index.ts'

const STUB_NOTE =
  'STUB — empty catch-all pool (CI/deploy). Full corpus: omit --stub. Fits Cloudflare Worker limits.'

export interface SkillIndexWrite {
  readonly count: number
  readonly bytes: number
  readonly out: string
}

/** The canonical shape of skills.index.ts — the one place it is spelled. */
export function skillIndexSource(index: readonly unknown[], note: string): string {
  return (
    '// AUTO-GENERATED by src/skill/router/build/index.ts — do not edit.\n' +
    `// ${note}\n` +
    "import type { SkillNode } from './resolve'\n\n" +
    `export const SKILL_INDEX: readonly SkillNode[] = ${JSON.stringify(index, null, 0)}\n`
  )
}

export function writeSkillIndexFile(
  cwd: string,
  index: readonly unknown[],
  note: string,
): SkillIndexWrite {
  const out = join(cwd, SKILL_INDEX_OUT)
  const file = skillIndexSource(index, note)
  mkdirSync(dirname(out), { recursive: true })
  writeFileSync(out, file)
  console.log(`skill-index: wrote ${index.length} skills → ${SKILL_INDEX_OUT} (${file.length} bytes)`)
  return { count: index.length, bytes: file.length, out: SKILL_INDEX_OUT }
}

/**
 * Empty expert pool — satisfies the static import for Payload migrate / OpenNext build without
 * baking 80MB into a Worker with a hard 3MB script limit.
 */
export function buildSkillIndexStub(cwd: string = process.cwd()): SkillIndexWrite {
  return writeSkillIndexFile(cwd, [], STUB_NOTE)
}

if (process.argv[1] && process.argv[1].endsWith('stub/index.ts')) buildSkillIndexStub()

