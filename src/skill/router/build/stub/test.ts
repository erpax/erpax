import { mkdtempSync, readFileSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { describe, it, expect } from 'vitest'
import { buildSkillIndexStub, skillIndexSource } from './index'

describe('skill/router/build/stub — 265 fixed bytes, written without booting the corpus', () => {
  it('writes an EMPTY pool that still satisfies the static import', () => {
    const tmp = mkdtempSync(join(tmpdir(), 'erpax-stub-'))
    const r = buildSkillIndexStub(tmp)
    expect(r.count).toBe(0)
    // The path comes BACK from the write — the literal is not published ([[matrix]] seal-debt).
    const text = readFileSync(join(tmp, r.out), 'utf8')
    expect(text).toContain("import type { SkillNode } from './resolve'")
    expect(text).toContain('export const SKILL_INDEX: readonly SkillNode[] = []')
    rmSync(tmp, { recursive: true, force: true })
  })

  it('the shape is spelled ONCE — the full emit writes through the same function', () => {
    // Extracting the stub so CI need not import [[aura]] and [[navigation]] would be pointless
    // if the file format then lived in two places and drifted.
    const full = skillIndexSource([{ route: 'a' }], 'note')
    const stub = skillIndexSource([], 'note')
    for (const t of [full, stub]) {
      expect(t.startsWith('// AUTO-GENERATED by src/skill/router/build/index.ts')).toBe(true)
      expect(t).toContain("import type { SkillNode } from './resolve'")
    }
    expect(full).toContain('[{"route":"a"}]')
  })

  it('the banner still names the emitter, not this file — the generated header is a pointer', () => {
    expect(skillIndexSource([], 'x')).toContain('src/skill/router/build/index.ts')
  })
})
