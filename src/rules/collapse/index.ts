/**
 * collapse — what can honestly become one table, decided by a theorem instead of a marker list.
 *
 * The telos is "collapse ~200 collections to a dense core". The measurement refuses it:
 *
 *   collections booted        231   (210 erpax hand-writes + 21 from plugins/Payload internals)
 *   IDENTICAL shapes            0   — no two are the same table
 *   provable SUBSETS            4   — of which THREE are semantic noise
 *   the one real merge          1   — customers ⊂ vendors, differing by exactly `bank`
 *
 * **Structural compression headroom is ~0.** The 210 shapes are genuinely distinct, so the collapse
 * everyone wants is a RE-MODELLING (deciding a customer and a vendor are both *parties*) — and no theorem
 * makes that decision. That is the honest boundary of "trust only theorems": a theorem tells you what you
 * cannot trust; it does not tell you what two tables MEAN.
 *
 * WHY payload-types AND @/collections, both:
 *   `payload-types.ts` is generated BY Payload from the real config — the shapes it actually booted, parsed
 *   with [[syntax]], not guessed. `@/collections` is what erpax HAND-WRITES. They disagree by 21, and the
 *   disagreement is the information: the 21 are plugin + internal tables (payload-migrations, carts,
 *   variants, forms…). Measuring against the generated types ALONE proposed collapsing `payload-migrations`
 *   into `lot-variants` — compressing a library's own migration table. **A collection erpax does not own is
 *   not erpax's to collapse.**
 *
 * WHY NOT the rosetta signature: `collectionSignature` scores a collection against a hand-picked marker list
 * (`money: ['amount','debit',…]`). It clusters 231 → 30 signatures (87% "compression") — and **47
 * collections match no marker at all**. A basis typed once, blind to whatever grew after it, is a FROZEN
 * rosetta: it reports what its author remembered. This measures the shapes themselves.
 *
 * Run: `tsx src/rules/collapse/index.ts`
 *
 * @standard RFC 9562 §5.8 — content-address (same content, same address)
 *
 * Composes [[syntax]] · [[merge]] · [[rules]] · [[law]].
 */
import ts from 'typescript'
import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { toUuid } from '@/uuid/matrix'

/** Fields every collection carries — they carry no shape, so they cannot distinguish one table from another. */
const NOISE = new Set(['id', 'createdAt', 'updatedAt', 'tenant', 'uuid', 'contentUuid', 'chainLeafUuid'])

export interface CollectionShape {
  readonly slug: string
  /** The content-address of the shape — same fields, same types ⇒ same uuid. A theorem, not a similarity. */
  readonly uuid: string
  readonly fields: ReadonlySet<string>
}

/** A collection whose every field another one also has: its rows FIT there, with nulls. Decidable. */
export interface Subset {
  readonly slug: string
  readonly host: string
  readonly extra: readonly string[]
}

/** Every collection's true shape, read from the types Payload GENERATED from the live config. */
export function shapesOf(cwd: string = process.cwd()): CollectionShape[] {
  const file = join(cwd, 'src/payload-types.ts')
  const text = readFileSync(file, 'utf8')
  const src = ts.createSourceFile(file, text, ts.ScriptTarget.ESNext, true)

  const ifaceOfSlug = new Map<string, string>()
  const ifaces = new Map<string, ts.InterfaceDeclaration>()
  const visit = (n: ts.Node): void => {
    if (ts.isInterfaceDeclaration(n)) {
      ifaces.set(n.name.text, n)
      if (n.name.text === 'Config') {
        for (const m of n.members) {
          if (ts.isPropertySignature(m) && m.name?.getText() === 'collections' && m.type && ts.isTypeLiteralNode(m.type)) {
            for (const c of m.type.members) {
              if (ts.isPropertySignature(c) && c.type) {
                ifaceOfSlug.set(c.name!.getText().replace(/['"]/g, ''), c.type.getText().replace(/\[\]$/, ''))
              }
            }
          }
        }
      }
    }
    ts.forEachChild(n, visit)
  }
  visit(src)

  const out: CollectionShape[] = []
  for (const [slug, iname] of ifaceOfSlug) {
    const i = ifaces.get(iname)
    if (!i) continue
    const members = i.members.filter(ts.isPropertySignature)
    const fields = new Set(members.map((m) => m.name!.getText().replace(/['"?]/g, '')).filter((n) => !NOISE.has(n)))
    if (fields.size === 0) continue
    const sig = members
      .map((m) => m.name!.getText().replace(/['"?]/g, '') + ':' + (m.type?.getText().replace(/\s+/g, ' ') ?? '?'))
      .filter((s) => !NOISE.has(s.split(':')[0]!))
      .sort()
      .join('|')
    out.push({ slug, uuid: toUuid(Buffer.from(sig, 'utf8')), fields })
  }
  return out
}

/**
 * Collections that are literally the same table — same fields, same types, colliding by content-address.
 *
 * @invariant a collision here is SAMENESS, not similarity — the fold decides, nothing is judged
 */
export function identicalShapes(cwd: string = process.cwd()): CollectionShape[][] {
  const byUuid = new Map<string, CollectionShape[]>()
  for (const s of shapesOf(cwd)) byUuid.set(s.uuid, [...(byUuid.get(s.uuid) ?? []), s])
  return [...byUuid.values()].filter((v) => v.length > 1)
}

/**
 * Collections whose fields are a strict subset of another's — their rows FIT, provably.
 *
 * HONEST BOUNDARY, and it is the finding: **fitting is not sameness.** Set inclusion is decidable, and it
 * decides the wrong question — a 2-field table fits inside almost anything. Measured over the live config it
 * returns 4, of which `payload-migrations ⊂ lot-variants` and `redirects ⊂ connections` are structurally true
 * and semantically absurd. It names CANDIDATES for a human; it never decides a merge.
 */
export function subsets(cwd: string = process.cwd()): Subset[] {
  const shapes = shapesOf(cwd)
  const out: Subset[] = []
  for (const a of shapes) {
    for (const b of shapes) {
      if (a.slug === b.slug || b.fields.size < a.fields.size) continue
      let fits = true
      for (const f of a.fields) if (!b.fields.has(f)) { fits = false; break }
      if (fits) out.push({ slug: a.slug, host: b.slug, extra: [...b.fields].filter((f) => !a.fields.has(f)) })
    }
  }
  return out.sort((x, y) => x.extra.length - y.extra.length)
}

