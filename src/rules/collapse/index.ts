  console.log(`\n  inverse-polarity pairs declared (by meaning): ${pairs.length} · shape-provable (theorem): ${theorem}`)
  for (const p of pairs) {
    console.log(`  ${p.verdict.padEnd(8)} ${p.a} ↔ ${p.b}  jaccard=${p.jaccard}  — ${p.why}`)
  }
