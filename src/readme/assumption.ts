/**
 * readme/assumption — drift + completeness gates for computed README faces.
 */
import { readFileSync, existsSync } from 'node:fs'
import { join } from 'node:path'
import { buildReadmeCorpusFrozenInputs, renderRootReadmeInWaves, generateFolderReadme } from './compute'
export { computeProseLiterals, BANNED_HAND_PROSE } from './assumption-literals'

export interface AssumptionVerdict { readonly ok: boolean; readonly violations: readonly string[] }
export interface ReadmeSectionStatus { readonly section: string; readonly present: boolean; readonly empty: boolean }
export interface ReadmeCompletenessMatrix { readonly kind: 'root' | 'folder'; readonly complete: boolean; readonly sections: readonly ReadmeSectionStatus[] }

const ROOT_SPECS = [
  ['orient', '## Orient to erpax'],
  ['diamond', '## the diamond'],
  ['pivot', '## [[pivot]]'],
  ['pivot-horo', '| digit | measure | atoms | principal facets |'],
  ['pivot-trinity', '### the trinity — every atom told three ways'],
  ['bonds', 'bonds'],
  ['analytics', '## corpus analytics'],
  ['standards', '[[standards]]'],
  ['bindings', '[[cloudflare]]'],
  ['quantum', '## corpus quantum thinking'],
  ['entropy', '## corpus entropy'],
] as const

export function readmeAssumptionViolations(readmePath: string, cwd = process.cwd()): AssumptionVerdict {
  let actual = ''
  try {
    actual = readFileSync(join(cwd, readmePath), 'utf8')
  } catch {
    return { ok: false, violations: ['missing'] }
  }
  let expected = ''
  if (readmePath === 'README.md') {
    expected = renderRootReadmeInWaves(cwd, buildReadmeCorpusFrozenInputs(cwd))
  } else if (readmePath.startsWith('src/') && readmePath.endsWith('/README.md')) {
    expected = generateFolderReadme(readmePath.slice(4, -9), cwd)
  } else {
    return { ok: false, violations: ['unknown-path'] }
  }
  const violations: string[] = []
  if (actual !== expected) violations.push('drift')
  if (!actual.includes('<!-- GENERATED by src/readme/index.ts')) violations.push('not-generated')
  return { ok: violations.length === 0, violations }
}

export function renderReadmeComplete(rendered: string, kind: 'root' | 'folder'): ReadmeCompletenessMatrix {
  const specs = kind === 'root' ? ROOT_SPECS : ([] as typeof ROOT_SPECS)
  const sections = specs.map(([section, marker]) => ({
    section,
    present: rendered.includes(marker),
    empty: false,
  }))
  return { kind, complete: sections.every((s) => s.present), sections }
}

export function readmeAssumptionScan(cwd = process.cwd(), atoms: readonly string[] = ['readme', 'diamond', 'pivot']) {
  const drifted: string[] = []
  for (const p of ['README.md', ...atoms.map((a) => `src/${a}/README.md`)]) {
    if (!existsSync(join(cwd, p))) {
      drifted.push(`${p}:missing`)
      continue
    }
    const v = readmeAssumptionViolations(p, cwd)
    if (!v.ok) drifted.push(`${p}:${v.violations.join(',')}`)
  }
  return { total: drifted.length, paths: drifted }
}
