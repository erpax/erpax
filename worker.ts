/**
 * Custom Cloudflare Worker entry — the `main` wrangler points at.
 *
 * A Durable Object binds ONLY if its class is a NAMED EXPORT of the
 * worker entry (`main`) — a workerd requirement. `@opennextjs/cloudflare`
 * generates `.open-next/worker.js` (regenerated each build, not editable),
 * which exports OpenNext's own DOs + the default `fetch`. This thin
 * wrapper is the conventional OpenNext custom-worker path: re-export
 * OpenNext's fetch + DOs, and add erpax's five Durable Objects so they
 * become named exports of `main` (ERPAX_DO / TENANT_QUOTA / RATE_LIMITER
 * / JOB_LOCK / AUDIT_CHAIN_DO in wrangler.jsonc). This closes the
 * "no such Durable Object class is exported from the worker" gap — the
 * AI quota counter + rate limiter + audit chain only work once bound.
 *
 * Earlier a side-effect import was tried and failed (it can't create a
 * named export); a re-export is the fix. See the `bindings` skill.
 *
 * @see https://opennext.js.org/cloudflare/howtos/custom-worker
 * @see src/ai/durable-objects.ts
 */
// ts-ignore, not ts-expect-error: `.open-next/worker.js` is a BUILD ARTIFACT, so it is absent in a
// clean checkout (the import errors, the directive is used) and present after a local build (the
// import resolves, and an expect-error would itself become an error). Only ignore tolerates both.
// eslint-disable-next-line @typescript-eslint/ban-ts-comment
// @ts-ignore — generated by `opennextjs-cloudflare build`, resolved by wrangler
import openNextHandler from './.open-next/worker.js'
import { runScheduledJobs, type CronEnv } from '@/run/cron'

// OpenNext's own Durable Objects (queue / sharded-tag-cache / bucket-cache).
// eslint-disable-next-line @typescript-eslint/ban-ts-comment
// @ts-ignore — generated, resolved by wrangler; see the note above on ignore vs expect-error
export * from './.open-next/worker.js'

