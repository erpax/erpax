#!/usr/bin/env node
// The files that describe erpax to others, generated from what they describe, so none can drift:
//
//   .claude-plugin/plugin.json, .claude-plugin/marketplace.json
//       ← package.json, and whether the repo holds any skills (SKILL.md under src)
//   .github/SPONSORS.md
//       ← package.json, .github/FUNDING.yml, Payload's generated Config (src/payload-types.ts),
//         src/migrations and the Lean proof record (inventory.generated.json)
//
// `pnpm generate:repo` writes them; `--check` exits 1 when a committed copy differs. The pre-commit
// hook writes them on every commit and `pnpm lint` checks them, so pre-push and CI refuse a stale copy.
// Change the source, never the output.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parse } from 'yaml'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const read = (path) => readFileSync(join(ROOT, path), 'utf8')
const json = (value) => `${JSON.stringify(value, null, 2)}\n`

export const INVENTORY = 'src/utilities/verify/lean/inventory.generated.json'

/** The repository's web address, from package.json `repository` (a string or `{ url }`). */
export const repositoryOf = (pkg) => {
  const url = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url
  if (!url) throw new Error('package.json needs "repository": the manifests and the sponsor page link to it.')
  return url.replace(/^git\+/, '').replace(/\.git$/, '')
}

/** The account that owns the repository: the first path segment of its address. */
export const ownerOf = (pkg) => {
  const url = new URL(repositoryOf(pkg))
  const name = url.pathname.split('/')[1]
  return { name, url: `${url.origin}/${name}` }
}

/** The collection slugs in Payload's generated `Config`, without Payload's own (`payload-*`). */
export const collectionsOf = (types) => {
  const block = /^export interface Config \{[\s\S]*?^ {2}collections: \{\n([\s\S]*?)^ {2}\};/m.exec(types)?.[1]
  if (!block) throw new Error('src/payload-types.ts has no Config.collections: run pnpm generate:types.')
  return [...block.matchAll(/^ {4}'?([\w-]+)'?: /gm)].map((m) => m[1]).filter((slug) => !slug.startsWith('payload-'))
}

/** Migration names, oldest first (the timestamp leads each name). */
export const migrationsOf = (files) => files.filter((f) => f.endsWith('.ts') && f !== 'index.ts').map((f) => f.replace(/\.ts$/, '')).sort()

/** Where FUNDING.yml sends a sponsor. A platform this does not know stops the run, so none is dropped silently. */
export const fundingLinksOf = (funding) =>
  Object.entries(funding ?? {}).flatMap(([platform, value]) => {
    const values = (Array.isArray(value) ? value : [value]).filter(Boolean)
    if (platform === 'github') return values.map((user) => ({ label: `GitHub Sponsors (@${user})`, url: `https://github.com/sponsors/${user}` }))
    if (platform === 'custom') return values.map((url) => ({ label: new URL(url).host, url }))
    throw new Error(`.github/FUNDING.yml: teach scripts/generate-repo.mjs the "${platform}" platform.`)
  })

export const pluginOf = (pkg, { hasSkills }) => ({
  name: pkg.name,
  version: pkg.version,
  description: pkg.description,
  author: pkg.author,
  homepage: pkg.homepage ?? repositoryOf(pkg),
  repository: repositoryOf(pkg),
  license: pkg.license,
  keywords: pkg.keywords ?? [],
  // The MCP connector is .mcp.json at the plugin root, which Claude Code loads without a key here.
  ...(hasSkills ? { skills: './src' } : {}),
})

export const marketplaceOf = (pkg) => ({
  name: pkg.name,
  version: pkg.version,
  description: pkg.description,
  owner: ownerOf(pkg),
  plugins: [{ name: pkg.name, source: './', description: pkg.description, version: pkg.version, author: pkg.author }],
})

export const sponsorsOf = ({ pkg, links, collections, migrations, inventory }) => {
  const { census, files, sealedAt } = inventory
  return [
    '<!-- Generated by scripts/generate-repo.mjs from package.json, .github/FUNDING.yml, src/payload-types.ts, src/migrations and the Lean proof record. Change those, not this page: the pre-commit hook rewrites it, and `pnpm lint` fails on a copy that differs. -->',
    '',
    `# Sponsor ${pkg.name}`,
    '',
    `${pkg.description}.`,
    '',
    `Sponsor through ${links.map((l) => `[${l.label}](${l.url})`).join(' or ')}.`,
    '',
    '## What it is today',
    '',
    'Each figure is computed from the source beside it whenever this page is generated.',
    '',
    '| Figure | Value | Computed from |',
    '| --- | --- | --- |',
    `| Version | ${pkg.version} | \`package.json\` |`,
    `| Collections | ${collections.length} | \`src/payload-types.ts\`, Payload's generated \`Config\`, without Payload's own \`payload-*\` |`,
    `| Migrations | ${migrations.length}, the latest \`${migrations.at(-1)}\` | \`src/migrations\` |`,
    `| Kernel-checked theorems | ${census.theorems} in ${files.length} files: ${census.axiomFree} axiom-free, ${census.standardAxioms} on Lean's standard axioms, ${census.stubbed} stubbed (sealed ${sealedAt}) | \`${INVENTORY}\` |`,
    `| License | ${pkg.license} | \`package.json\` |`,
    '',
    `Source: [${repositoryOf(pkg).replace(/^https:\/\//, '')}](${repositoryOf(pkg)})`,
    '',
  ].join('\n')
}

/** Every output, as the sources say it should read. */
export const generate = () => {
  const pkg = JSON.parse(read('package.json'))
  const hasSkills = readdirSync(join(ROOT, 'src'), { recursive: true }).some((f) => String(f).endsWith('SKILL.md'))
  const page = sponsorsOf({
    pkg,
    links: fundingLinksOf(parse(read('.github/FUNDING.yml'))),
    collections: collectionsOf(read('src/payload-types.ts')),
    migrations: migrationsOf(readdirSync(join(ROOT, 'src/migrations'))),
    inventory: JSON.parse(read(INVENTORY)),
  })
  return {
    '.claude-plugin/plugin.json': json(pluginOf(pkg, { hasSkills })),
    '.claude-plugin/marketplace.json': json(marketplaceOf(pkg)),
    '.github/SPONSORS.md': page,
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check')
  const differ = []
  for (const [path, content] of Object.entries(generate())) {
    if ((existsSync(join(ROOT, path)) ? read(path) : '') === content) continue
    if (check) differ.push(path)
    else writeFileSync(join(ROOT, path), content)
  }
  if (differ.length) {
    console.error(`Generated files differ from their sources: ${differ.join(', ')}. Run pnpm generate:repo and commit the result.`)
    process.exit(1)
  }
}
