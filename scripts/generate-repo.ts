// The files that describe erpax to others, generated from what they describe, so none can drift:
//
//   README.md
//       ← package.json, CITATION.cff (the DOI and the licensing contact), Payload's generated Config
//         (src/payload-types.ts), src/migrations and the Lean proof record with its sources
//   .github/SPONSORS.md
//       ← package.json, .github/FUNDING.yml and the same figures as the README
//   .claude-plugin/plugin.json, .claude-plugin/marketplace.json
//       ← package.json, and whether the repo holds any skills (SKILL.md under src)
//
// `pnpm generate:repo` writes them; `--check` exits 1 when a committed copy differs. The pre-commit
// hook writes them on every commit and `pnpm lint` checks them, so pre-push and CI refuse a stale copy.
// Change the source (or this template), never the output.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { parse } from 'yaml'

import { claySection, clayWitnesses, INVENTORY_PATH, type ProofInventory } from '@/utilities/verify/inventory'

const ROOT = fileURLToPath(new URL('..', import.meta.url))
const read = (path: string): string => readFileSync(join(ROOT, path), 'utf8')
const json = (value: unknown): string => `${JSON.stringify(value, null, 2)}\n`
const LEAN_DIR = 'src/utilities/verify/lean'

export interface Pkg {
  name: string
  version: string
  description: string
  license: string
  author?: { name: string; url?: string }
  homepage?: string
  repository?: string | { url?: string }
  keywords?: string[]
  scripts: Record<string, string>
  dependencies?: Record<string, string>
  devDependencies?: Record<string, string>
  engines?: Record<string, string>
}

/** A value a generated file states: missing, it stops the run instead of printing a blank. */
const required = <T>(value: T | undefined | null, what: string): T => {
  if (value === undefined || value === null || value === '') throw new Error(`generate-repo: ${what} is missing.`)
  return value
}

const note = (sources: string): string =>
  `<!-- Generated by scripts/generate-repo.ts from ${sources}. Change those, not this file: the pre-commit hook rewrites it, and \`pnpm lint\` fails on a copy that differs. -->`

/** The repository's web address, from package.json `repository` (a string or `{ url }`). */
export const repositoryOf = (pkg: Pkg): string => {
  const url = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url
  return required(url, 'package.json "repository"').replace(/^git\+/, '').replace(/\.git$/, '')
}

/** The account that owns the repository: the first path segment of its address. */
export const ownerOf = (pkg: Pkg): { name: string; url: string } => {
  const url = new URL(repositoryOf(pkg))
  const name = required(url.pathname.split('/')[1], 'the repository owner')
  return { name, url: `${url.origin}/${name}` }
}

/** The collection slugs in Payload's generated `Config`, without Payload's own (`payload-*`). */
export const collectionsOf = (types: string): string[] => {
  const block = required(/^export interface Config \{[\s\S]*?^ {2}collections: \{\n([\s\S]*?)^ {2}\};/m.exec(types)?.[1], 'Config.collections in src/payload-types.ts (run pnpm generate:types)')
  return [...block.matchAll(/^ {4}'?([\w-]+)'?: /gm)].map((m) => m[1] as string).filter((slug) => !slug.startsWith('payload-'))
}

/** Migration names, oldest first (the timestamp leads each name). */
export const migrationsOf = (files: readonly string[]): string[] =>
  files.filter((f) => f.endsWith('.ts') && f !== 'index.ts').map((f) => f.replace(/\.ts$/, '')).sort()

/** Where FUNDING.yml sends a sponsor. A platform this does not know stops the run, so none is dropped silently. */
export const fundingLinksOf = (funding: Record<string, unknown> | null): { label: string; url: string }[] =>
  Object.entries(funding ?? {}).flatMap(([platform, value]) => {
    const values = (Array.isArray(value) ? value : [value]).filter(Boolean).map(String)
    if (platform === 'github') return values.map((user) => ({ label: `GitHub Sponsors (@${user})`, url: `https://github.com/sponsors/${user}` }))
    if (platform === 'custom') return values.map((url) => ({ label: new URL(url).host, url }))
    throw new Error(`.github/FUNDING.yml: teach scripts/generate-repo.ts the "${platform}" platform.`)
  })

export interface Figures {
  pkg: Pkg
  collections: readonly string[]
  migrations: readonly string[]
  inventory: ProofInventory
}

/** A table cell: a pipe inside a value (a version range such as `^24 || >=26`) would end the cell, so pipes are
 * escaped, and backslashes first, or a value ending in one would undo the escape. */
const cell = (value: string): string => value.replace(/\\/g, '\\\\').replace(/\|/g, '\\|')

/** The figures table the README and the sponsor page both show, each value beside its source. */
export const figureRows = ({ pkg, collections, migrations, inventory }: Figures): string[] => {
  const dep = (name: string): string => cell(required(pkg.dependencies?.[name] ?? pkg.devDependencies?.[name], `package.json dependency "${name}"`))
  const { census, files, sealedAt } = inventory
  return [
    '| Figure | Value | Computed from |',
    '| --- | --- | --- |',
    `| Version | ${cell(pkg.version)} | \`package.json\` |`,
    `| Payload | ${dep('payload')} | \`package.json\` |`,
    `| Next.js | ${dep('next')} | \`package.json\` |`,
    `| Node | ${cell(required(pkg.engines?.node, 'package.json engines.node'))} | \`package.json\` |`,
    `| Collections | ${collections.length} | \`src/payload-types.ts\`, Payload's generated \`Config\`, without Payload's own \`payload-*\` |`,
    `| Migrations | ${migrations.length}, the latest \`${required(migrations.at(-1), 'a migration')}\` | \`src/migrations\` |`,
    `| Kernel-checked theorems | ${census.theorems} in ${files.length} files: ${census.axiomFree} axiom-free, ${census.standardAxioms} on Lean's standard axioms, ${census.stubbed} stubbed (sealed ${sealedAt}) | \`${INVENTORY_PATH}\` |`,
    `| License | ${cell(pkg.license)} | \`package.json\` |`,
  ]
}

export const readmeOf = (f: Figures & { doi: string; contact?: string; clay: string }): string => {
  const { pkg } = f
  const repo = repositoryOf(pkg)
  // what the page tells a reader to run or open must exist
  for (const script of ['dev', 'erpax']) required(pkg.scripts[script], `package.json script "${script}" (the README tells readers to run it)`)
  for (const file of ['AGENTS.md', 'LICENSE']) if (!existsSync(join(ROOT, file))) throw new Error(`generate-repo: the README links ${file}, which does not exist.`)
  return [
    note('package.json, CITATION.cff, src/payload-types.ts, src/migrations and the Lean proof record'),
    '',
    `# ${pkg.name}`,
    '',
    `> ${pkg.description}`,
    '',
    `[![Deploy to Cloudflare](https://deploy.workers.cloudflare.com/button)](https://deploy.workers.cloudflare.com/?url=${encodeURIComponent(repo)}) [![DOI](https://zenodo.org/badge/DOI/${f.doi}.svg)](https://doi.org/${f.doi})`,
    '',
    '## Start',
    '',
    '```bash',
    'pnpm install',
    'pnpm dev                  # http://localhost:3000/admin: the first user you create is the super-admin',
    'pnpm erpax login --local  # sign an agent in to the MCP gateway at /api/mcp',
    '```',
    '',
    '[AGENTS.md](AGENTS.md) is the guide for people and agents working in this repository.',
    '',
    '## What it is today',
    '',
    'Each figure is computed from the source beside it whenever this file is generated.',
    '',
    ...figureRows(f),
    '',
    f.clay,
    '## Commands',
    '',
    `${Object.keys(pkg.scripts).map((s) => `\`pnpm ${s}\``).join(' · ')}. \`package.json\` holds what each runs, and [AGENTS.md](AGENTS.md) says when to use them.`,
    '',
    '## License',
    '',
    `[${pkg.license}](LICENSE)${f.contact ? `. Commercial terms: ${f.contact}` : ''}.`,
    '',
  ].join('\n')
}

export const sponsorsOf = (f: Figures & { links: readonly { label: string; url: string }[] }): string =>
  [
    note('package.json, .github/FUNDING.yml, src/payload-types.ts, src/migrations and the Lean proof record'),
    '',
    `# Sponsor ${f.pkg.name}`,
    '',
    `${f.pkg.description}.`,
    '',
    `Sponsor through ${required(f.links.length ? f.links : undefined, 'a funding link in .github/FUNDING.yml').map((l) => `[${l.label}](${l.url})`).join(' or ')}.`,
    '',
    '## What it is today',
    '',
    'Each figure is computed from the source beside it whenever this page is generated.',
    '',
    ...figureRows(f),
    '',
    `Source: [${repositoryOf(f.pkg).replace(/^https:\/\//, '')}](${repositoryOf(f.pkg)})`,
    '',
  ].join('\n')

export const pluginOf = (pkg: Pkg, { hasSkills }: { hasSkills: boolean }) => ({
  name: pkg.name,
  version: pkg.version,
  description: pkg.description,
  author: pkg.author,
  homepage: pkg.homepage ?? repositoryOf(pkg),
  repository: repositoryOf(pkg),
  license: pkg.license,
  keywords: pkg.keywords ?? [],
  // The MCP connector is .mcp.json at the plugin root, which Claude Code loads without a key here.
  ...(hasSkills ? { skills: './src' } : {}),
})

export const marketplaceOf = (pkg: Pkg) => ({
  name: pkg.name,
  version: pkg.version,
  description: pkg.description,
  owner: ownerOf(pkg),
  plugins: [{ name: pkg.name, source: './', description: pkg.description, version: pkg.version, author: pkg.author }],
})

/** Every output, as the sources say it should read. */
export const generate = (): Record<string, string> => {
  const pkg = JSON.parse(read('package.json')) as Pkg
  const citation = parse(read('CITATION.cff')) as { doi?: string; contact?: { email?: string }[] }
  const inventory = JSON.parse(read(INVENTORY_PATH)) as ProofInventory
  const sources = Object.fromEntries(
    readdirSync(join(ROOT, LEAN_DIR)).filter((f) => f.endsWith('.lean')).map((f) => [f, read(`${LEAN_DIR}/${f}`)]),
  )
  const figures: Figures = {
    pkg,
    collections: collectionsOf(read('src/payload-types.ts')),
    migrations: migrationsOf(readdirSync(join(ROOT, 'src/migrations'))),
    inventory,
  }
  const hasSkills = readdirSync(join(ROOT, 'src'), { recursive: true }).some((f) => String(f).endsWith('SKILL.md'))
  return {
    'README.md': readmeOf({
      ...figures,
      doi: required(citation.doi, 'CITATION.cff "doi"'),
      contact: citation.contact?.[0]?.email,
      clay: claySection(clayWitnesses(inventory, sources), inventory),
    }),
    '.github/SPONSORS.md': sponsorsOf({ ...figures, links: fundingLinksOf(parse(read('.github/FUNDING.yml')) as Record<string, unknown> | null) }),
    '.claude-plugin/plugin.json': json(pluginOf(pkg, { hasSkills })),
    '.claude-plugin/marketplace.json': json(marketplaceOf(pkg)),
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const check = process.argv.includes('--check')
  const differ: string[] = []
  for (const [path, content] of Object.entries(generate())) {
    if ((existsSync(join(ROOT, path)) ? read(path) : '') === content) continue
    if (check) differ.push(path)
    else writeFileSync(join(ROOT, path), content)
  }
  if (differ.length) {
    console.error(`Generated files differ from their sources: ${differ.join(', ')}. Run pnpm generate:repo and commit the result.`)
    process.exit(1)
  }
}
