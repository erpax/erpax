#!/usr/bin/env node
/**
 * emit-license — CITATION.cff is the single source for the facts about this work, because it is the
 * file the outside world reads. Restating the SPDX, the source URL, the licensing contact or the
 * DOI in TypeScript creates a second source that drifts ([[rules]]/drift), and an `export const` of
 * an external fact is seal-debt besides ([[matrix]]/constants-audit) — it cannot be computed from
 * the fold, because it was decided outside it.
 *
 *   node scripts/emit-license.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const cff = readFileSync(join(root, 'CITATION.cff'), 'utf8')

const one = (re, what) => {
  const m = re.exec(cff)
  if (!m) {
    console.error(`✖ CITATION.cff declares no ${what}`)
    process.exit(1)
  }
  return m[1]
}

const spdx = one(/^license:\s*(\S+)/m, 'license:')
const source = one(/^repository-code:\s*"([^"]+)"/m, 'repository-code:')
const contact = one(/^contact:\n\s+-\s+email:\s*"([^"]+)"/m, 'contact: email')
const concept = one(/^doi:\s*"([^"]+)"/m, 'doi:')
const versions = [...cff.matchAll(/value:\s*"(10\.\d{4,9}\/[^"]+)"/g)].map((m) => m[1])
const version = versions.find((v) => v !== concept) ?? concept

writeFileSync(
  join(root, 'src/algebra/license/generated.ts'),
  `/**
 * AUTO-GENERATED by scripts/emit-license.mjs from CITATION.cff — do not edit.
 *
 * Every value here is an EXTERNAL fact: a licence identifier, a repository, a contact, an
 * identifier a registration agency assigned. None can be computed from the corpus fold, so none may
 * be typed twice — CITATION.cff is what the world reads, and this face is read from it.
 *
 * Re-run: node scripts/emit-license.mjs
 */

/** SPDX identifier — ONE licence, every path. */
export const ERPAX_SPDX = '${spdx}' as const

/** Where the corpus lives, for the BY-NC-ND §3(a)(1) attribution link. */
export const SOURCE_URL = '${source}' as const

/** The commercial-licence route. NC means commercial use needs a separate licence. */
export const LICENSE_CONTACT = '${contact}' as const

/** The CONCEPT doi — every version of this work. */
export const ERPAX_DOI = '${concept}' as const

/** The doi of the most recently deposited VERSION. */
export const ERPAX_VERSION_DOI = '${version}' as const
`,
)
console.log(`emitted src/algebra/license/generated.ts — ${spdx} · ${source} · ${contact} · ${concept} / ${version}`)
